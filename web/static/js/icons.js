/** icon returns an SVG element for one of the names above. */
export function icon(name, cls = '') {
    const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', '0 0 24 24');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('class', ('icon ' + cls).trim());
    svg.innerHTML = PATHS[name] || PATHS.info;
    return svg;
}

/** iconHTML is the string form, for template literals. */
export function iconHTML(name, cls = '') {
    return `<svg viewBox="0 0 24 24" aria-hidden="true" class="icon ${cls}">${PATHS[name] || PATHS.info}</svg>`;
}

/** hydrateIcons swaps every <i data-icon="name"> placeholder for its SVG. */
export function hydrateIcons(root = document) {
    root.querySelectorAll('i[data-icon]').forEach((el) => {
        el.replaceWith(icon(el.dataset.icon, el.className));
    });
}
